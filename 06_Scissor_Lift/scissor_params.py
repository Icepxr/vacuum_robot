"""
scissor_params.py — พารามิเตอร์กลางของกลไก scissor lift 1 servo
โครงการ: หุ่นดูดฝุ่นอเนกประสงค์ (MRC-001) — เสายกกล้อง

หน่วย: มิลลิเมตร (mm), นิวตัน (N), องศา (deg) เว้นแต่ระบุไว้เป็นอย่างอื่น
ทุกไฟล์อื่น (scissor_analysis.py, scissor_cad.py) import จากไฟล์นี้ไฟล์เดียว
แก้ตัวเลขที่นี่ที่เดียวแล้วรันใหม่ทั้งชุด
"""

import math

# ============================================================
# 1. ข้อกำหนดจากโจทย์ (requirements)
# ============================================================
H_EXTENDED_TARGET = 500.0   # mm   ความสูงยกสุด (ผิวบนแพลตฟอร์มจากผิวบนฐาน)
STOW_X            = 100.0   # mm   พื้นที่เก็บ แกน X
STOW_Y            = 100.0   # mm   พื้นที่เก็บ แกน Y
M_PAYLOAD         = 0.060   # kg   กล้อง + แพลตฟอร์มยึด

G = 9.81                    # m/s^2

# ============================================================
# 2. เรขาคณิต scissor
# ============================================================
# H    = N_STAGES * L_LINK * sin(theta)   ความสูงยก
# span = L_LINK * cos(theta)              ความยาวแนวนอนที่กินตอนพับ
#
# ที่มาของ 7 ชั้น x 80 mm (เคยลอง 6 x 85 แล้วไม่ผ่าน):
#   6 ชั้น x 85 mm → span ตอนพับ 83.7 mm + ครีบหมุด 8 + แคร่ 8 = 99.7 mm
#     → กินฐาน 100 mm หมดพอดี ไม่เหลือเนื้อให้โครงสร้างเลย ✗
#     → แถม crank ต้องรัศมี 33.6 mm ทำให้ร่อง yoke กว้าง 87 mm ชนขอบฐาน ✗
#   7 ชั้น x 80 mm → span ตอนพับ 79.2 mm + 16 = 95.2 mm  เหลือขอบ 4.8 mm ✓
#     → crank รัศมีแค่ 21.7 mm ร่อง yoke กว้าง 53 mm อยู่กลางฐานสบาย ✓
#     → ความสูงตอนพับ 77.9 mm → รวมทั้งโมดูล ~95 mm = อยู่ในลูกบาศก์ 100³ ✓
N_STAGES   = 7          # จำนวนชั้น X
L_LINK     = 80.0       # mm  ระยะ pin-to-pin ของแขนหนึ่งท่อน
THETA_MAX  = 58.8       # deg มุมตอนยกสุด
#   เลือกจาก "ความสูงรวมของโมดูล" = 500 mm พอดี (ไม่ใช่แค่ระยะกอง scissor):
#   Z_PIN(11) + 7*80*sin(58.8°)=479.0 + ช่องว่างใต้แพลตฟอร์ม(6) + หนาแพลตฟอร์ม(3) = 499.0 mm
THETA_MIN  = 8.0        # deg มุมตอนพับเก็บ → H = 7*80*sin(8.0°)  =  77.9 mm

# แขน (link) — ชิ้นพิมพ์ 3D
#
# *** ข้อจำกัดที่สำคัญที่สุดของความกว้างแขน ***
# ตอนพับสุด แขน "ชั้นเดียวกัน" ของชั้นที่ติดกันจะขนานกันและห่างกันแค่
#     d = L·sin(θ_min)·cos(θ_min) = 80·sin8°·cos8° = 11.02 mm
# ถ้า LINK_W > d แขนจะชนกันตอนพับ (ตรวจพบตอนสร้าง CAD จริง — 14 mm ชนแน่นอน)
# จึงต้อง LINK_W < 11.02 − ระยะเผื่อ  →  เลือก 10.0 mm (เหลือช่อง 1.02 mm)
LINK_W     = 10.0       # mm  ความกว้างแขน
LINK_T     = 3.2        # mm  ความหนาแขน (= 8 layers @0.4 หรือ 4 perimeters)
LINK_END_R = LINK_W / 2 # mm  รัศมีปลายมน

# หมุด/สลัก M3
PIN_D      = 3.2        # mm  รูสลัก (M3 clearance)
PIN_HEAD_D = 6.4        # mm
WASHER_T   = 0.8        # mm  ระยะเผื่อระหว่างแขนต่อจุด

# ระยะห่างระหว่างระนาบ scissor ซ้าย-ขวา (สองชุดขนานกัน = กันบิด)
TRACK_Y    = 62.0       # mm  ระยะ center-to-center ของสองระนาบ

# ============================================================
# 3. ฐาน (base) และแพลตฟอร์ม (platform)
# ============================================================
BASE_X     = 100.0
BASE_Y     = 100.0
BASE_T     = 5.0        # mm  ความหนาฐาน (ต้องรับแรงดึงแนวนอนจาก slider)
PLAT_X     = 96.0
PLAT_Y     = 96.0
PLAT_T     = 3.0

RAIL_W     = 10.0       # mm  ความกว้างร่องราง slider
RAIL_DEPTH = 3.0        # mm

# ============================================================
# 4. ระบบขับ: MG996R + SCOTCH YOKE
# ============================================================
# ทำไมถึงเลือก scotch yoke ไม่ใช่ crank + ก้านต่อ (con-rod):
#   crank+conrod กินความยาวรวม (r + l) ≈ 114 mm > ฐาน 100 mm — ใส่ไม่ลง
#   scotch yoke ไม่มีก้านต่อ กินแค่ 2r = 67 mm → อยู่ในฐาน 100x100 ได้สบาย
#   และยังคง "จุดศูนย์ตาย" ทั้งสองปลาย ซึ่งเป็นหัวใจของดีไซน์นี้
#
#   x_slider(φ) = x_c + r·cos(φ)        →  dx/dφ = -r·sin(φ)
#   ที่ φ=0 และ φ=180°  dx/dφ = 0  → ได้เปรียบเชิงกลอนันต์ + ล็อกตัวเอง

SLIDER_STROKE = L_LINK * (math.cos(math.radians(THETA_MIN))
                          - math.cos(math.radians(THETA_MAX)))

CRANK_PHI_OFFSET = 9.0              # deg เยื้องจากจุดศูนย์ตายตอนพับสุด
                                    #     >0 เพื่อให้เซอร์โวมี "แรงงัด" มหาศาลตอนเริ่มยก
CRANK_R    = SLIDER_STROKE / (1.0 + math.cos(math.radians(CRANK_PHI_OFFSET)))

YOKE_SLOT_W  = 10.2      # mm  ความกว้างร่อง yoke (ลูกปืน 623ZZ OD 10 mm)
YOKE_PLATE_T = 6.0       # mm  ความหนาแผ่น yoke
BEARING_OD   = 10.0      # mm  623ZZ  (3 x 10 x 4)
BEARING_ID   = 3.0
BEARING_W    = 4.0

# MG996R (6.0 V)
SERVO_STALL_TORQUE = 11.0   # kgf*cm  ค่าสเปคที่ 6V
SERVO_TORQUE_NM    = SERVO_STALL_TORQUE * 0.0980665   # N*m
SERVO_TRAVEL_DEG   = 180.0  # deg  ช่วงหมุนใช้งานได้จริง
SERVO_STALL_A      = 2.5    # A    กระแสตอน stall ที่ 6V
SERVO_IDLE_A       = 0.01   # A

# ============================================================
# 5. สมมติฐานเชิงกล
# ============================================================
ETA_JOINT   = 0.65    # ประสิทธิภาพรวมของข้อต่อ scissor (ความฝืดหมุด 12+ จุด)
ETA_CRANK   = 0.90    # ประสิทธิภาพ crank-slider
SF_TARGET   = 2.0     # safety factor ที่ต้องการบนแรงบิดเซอร์โว

RHO_PETG    = 1.27e-3   # g/mm^3
E_PETG      = 2000.0    # MPa  Young's modulus
SIGMA_PETG  = 45.0      # MPa  แรงดึงที่จุดคราก (พิมพ์ตามยาว)
SIGMA_ALLOW = 15.0      # MPa  แรงที่ยอมให้ (เผื่อ anisotropy + creep, SF~3)

# ============================================================
# 6. ข้อมูลหุ่น (จาก sim_CoG_scissor.ipynb) สำหรับเช็คเสถียรภาพ
# ============================================================
ROBOT_COMPONENTS = [
    # (ชื่อ, มวล kg, x m, y m, z m)
    ("ฐาน/โครง chassis",        1.200,  0.000,  0.000, 0.030),
    ("แบตเตอรี่ Li-ion",        0.450, -0.060,  0.000, 0.045),
    ("Raspberry Pi 5",          0.050, -0.020,  0.000, 0.060),
    ("ESP32-S3 + บอร์ด",        0.030,  0.050,  0.030, 0.055),
    ("มอเตอร์ล้อ ซ้าย",         0.055,  0.000,  0.090, 0.030),
    ("มอเตอร์ล้อ ขวา",          0.055,  0.000, -0.090, 0.030),
    ("มอเตอร์ดูด BLDC",         0.150, -0.080,  0.000, 0.050),
    ("แปรงกลาง roller",         0.120,  0.110,  0.000, 0.025),
    ("LiDAR LD19",              0.100, -0.030,  0.000, 0.085),
]
SUPPORT = dict(front=0.110, rear=0.110, left=0.100, right=0.100)  # m
WHEEL_BASE_Z = 0.0

# ============================================================
# ฟังก์ชันช่วย
# ============================================================
def height_at(theta_deg: float) -> float:
    """ความสูงยก (mm) ที่มุม theta"""
    return N_STAGES * L_LINK * math.sin(math.radians(theta_deg))

def span_at(theta_deg: float) -> float:
    """ความยาวแนวนอนที่กิน (mm) ที่มุม theta"""
    return L_LINK * math.cos(math.radians(theta_deg))

def slider_x_at(theta_deg: float) -> float:
    """ตำแหน่ง slider วัดจากจุดหมุนตายตัว (mm)"""
    return span_at(theta_deg)

if __name__ == "__main__":
    print(f"ยกสุด  θ={THETA_MAX}° → H = {height_at(THETA_MAX):.1f} mm, "
          f"span = {span_at(THETA_MAX):.1f} mm")
    print(f"พับสุด θ={THETA_MIN}° → H = {height_at(THETA_MIN):.1f} mm, "
          f"span = {span_at(THETA_MIN):.1f} mm")
    print(f"slider stroke = {SLIDER_STROKE:.1f} mm → crank R = {CRANK_R:.1f} mm")

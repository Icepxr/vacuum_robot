// ── ขา GPIO — ตรงกับ system_architecture.md §3.2 ────────────
// §3.2 ระบุชัดว่าขานี้เป็น "GPIO ธรรมดา ไม่ผูก LEDC"
// วงจรที่ขา: R 100 Ω อนุกรมเข้าเกต + pull-down 10 kΩ ลงกราวด์ + ไดโอด SS34 คร่อมโหลด
// ⚠ ตัวที่กัน blower ออกตัวตอนบูตจริงๆ คือ pull-down 10 kΩ ไม่ใช่โค้ด —
//   ช่วง ~300 ms ของ bootloader ก่อนถึง setup() ขายังลอยอยู่
constexpr int PIN_SUCTION_EN = 21;

// ── สเปกของ blower ที่ใช้จริง ────────────────────────────────
// AVC BA10033B12U · 12 V · 2.4 A (28.8 W) · centrifugal 97 mm  [สเปก]
constexpr float BLOWER_V_NOM      = 12.0f;
constexpr float BLOWER_I_RATED_A  = 2.4f;
// เกณฑ์ผ่านของกระแส: 2.4 × 1.15 = 2.76 A (test_design §1.1 ตารางที่ 1)
constexpr float BLOWER_I_LIMIT_A  = 2.76f;

// ── โหมดการขับ ───────────────────────────────────────────────
// §3.5 สรุปว่า "เริ่มด้วยเปิด-ปิดอย่างเดียว" เพราะไล่ FSM ทั้ง 12 state
// แล้วไม่มี state ไหนใช้กำลังดูดระดับกลาง
//
// 🔴 ห้าม PWM ที่ 20 kHz เด็ดขาด — §3.5 คำนวณไว้ว่าจะทิ้งความร้อน 1.066 W
//    ทำให้ MOSFET ร้อนขึ้น +66 °C  (25 Hz ทิ้ง 0.346 W = +21 °C)
//    ⚠ ทั้งสี่ตัวเลขเป็น [ประมาณการ] — คำนวณจาก R_DS(on) 60 mΩ (ไฟล์ 10 ข้อ P1)
//       และ R_th 60 °C/W (ข้อ P2) ซึ่งไฟล์ 10 ระบุว่าเป็นการเดาทั้งคู่
//    เหตุผลที่สองไม่เกี่ยวกับความร้อน: blower เป็นมอเตอร์ไร้แปรงถ่านที่มีวงจรขับ
//    ในตัว การสับไฟ 20,000 ครั้ง/วินาที คือการปลุก-ดับวงจรของมันเอง
constexpr uint32_t PWM_FREQ_DEFAULT_HZ = 25;    // §3.5 timer T3
constexpr uint32_t PWM_FREQ_MIN_HZ     = 10;
constexpr uint32_t PWM_FREQ_MAX_HZ     = 50;    // เพดานแข็ง — เกินนี้ปฏิเสธ

// ⚠ §3.5 เขียนไว้ว่า T3 ใช้ 10-bit แต่ **ตั้งค่านั้นไม่ได้จริงบน ESP32-S3**
//   ตัวหารของ LEDC ต้องอยู่ในช่วง [256, 262143] และ
//     div = (f_clk × 256) / (freq × 2^res)
//   ที่ 25 Hz · 10-bit บน APB 80 MHz ได้ 800,000 → เกินเพดาน ตั้งไม่ได้
//   ที่ 10 Hz (ขอบล่างที่โค้ดนี้อนุญาต) ต้องใช้อย่างน้อย 13 บิต
//   → เลือก 13 บิต เพื่อให้ทั้งช่วง 10–50 Hz ใช้ได้ด้วยค่าเดียว
//   รายละเอียดและตารางเต็ม: 08_การคำนวณ/17 · ความขัดแย้งกับ §3.5 บันทึกไว้ที่ไฟล์ 10 ข้อ C15
constexpr uint8_t  PWM_RES_BITS        = 13;    // ≤ 14 = เพดานของ ESP32-S3
constexpr int      PWM_MAX             = (1 << PWM_RES_BITS) - 1;   // 8191

// ── ขีดจำกัดความปลอดภัยของการทดสอบ ──────────────────────────
constexpr uint32_t MAX_ON_MS    = 120000;  // คำสั่ง on เปิดค้างได้ไม่เกิน 2 นาที
constexpr uint32_t DEADMAN_MS   =  60000;  // ไม่มีคำสั่งใหม่เกินนี้ = ปิดเอง
                                           // ⚠ ต้องน้อยกว่า MAX_ON_MS ไม่งั้นเป็นโค้ดตาย
// ขั้น S2 ต้องเปิดค้างจนอุณหภูมิ MOSFET นิ่ง ซึ่งนานกว่า MAX_ON_MS
// จึงมีคำสั่ง `heat` แยกไว้เฉพาะ พร้อมปุ่มหยุดกลางคัน
constexpr uint32_t MAX_HEAT_MS  = 600000;  // 10 นาที
